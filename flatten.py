"""Build a single-file submission: papers/B_AEGIS_TNSM/submission/main.tex (+ figures/, compiled main.pdf, zip).

Every \\input (numbers, tables, sections, TikZ system-model and autoencoder figures) is inlined, the planning
appendix and internal comments are removed, and the bibliography is inlined from the .bbl (no .bib needed).
The matplotlib graphs stay as PDF files in submission/figures/ (\\includegraphics).

    python scripts/flatten.py <path-to-main.bbl>
"""
from __future__ import annotations

import re
import shutil
import sys
import zipfile
from pathlib import Path

PAPER = Path(__file__).resolve().parents[2]
OUT = PAPER / "submission"


def strip_comment_lines(text: str) -> str:
    """Drop full-line comments (keeps % inside lines, e.g. \\%)."""
    return "\n".join(l for l in text.splitlines() if not l.lstrip().startswith("%"))


def inline(text: str, base: Path) -> str:
    def rep(m):
        name = m.group(1)
        f = base / (name if name.endswith(".tex") else name + ".tex")
        body = strip_comment_lines(f.read_text())
        return f"% ---- begin {f.relative_to(PAPER)} ----\n" + inline(body, base) + f"\n% ---- end {f.relative_to(PAPER)} ----"
    return re.sub(r"\\input\{([^}]+)\}", rep, text)


def main(bbl: Path):
    src = (PAPER / "main.tex").read_text()
    # planning appendix (internal, not for submission)
    i = src.find("%% ==============================================================\n%%  PLANNING APPENDIX")
    if i >= 0:
        src = src[:i] + "\\end{document}\n"
    src = re.sub(r"\\newif\\ifshowplan[^\n]*\n", "", src)
    src = re.sub(r"\\newcommand\{\\todo\}[^\n]*\n", "", src)
    src = re.sub(r"%\s*<--[^\n]*", "", src)                         # internal notes after code
    head = ("% AEGIS-FL -- IEEE Transactions on Network and Service Management (single-file submission).\n"
            "% Generated by code/scripts/flatten.py from the modular sources; all numbers come from the\n"
            "% experiment logs (code/results). Graphs: figures/*.pdf. Compile: pdflatex main (twice).\n")
    src = strip_comment_lines(src)
    src = inline(src, PAPER)
    src = src.replace("\\bibliographystyle{IEEEtran}\n\\bibliography{references}", bbl.read_text().strip())
    OUT.mkdir(exist_ok=True)
    (OUT / "figures").mkdir(exist_ok=True)
    (OUT / "main.tex").write_text(head + src + "\n")
    used = set(re.findall(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}", src))
    for g in sorted(used):
        shutil.copy(PAPER / "figures" / (g if g.endswith(".pdf") else g + ".pdf"), OUT / "figures")
    print("main.tex lines:", src.count("\n"), "| figures:", sorted(used))


if __name__ == "__main__":
    main(Path(sys.argv[1]))
